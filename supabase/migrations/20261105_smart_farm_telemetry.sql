-- Smart Farm telemetry schema
-- V-NET2.0 ingestion is performed server-side by Google Apps Script.
-- Browser clients are read-only and must authenticate with Supabase Auth.

CREATE TABLE IF NOT EXISTS public.farm_devices (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  provider TEXT NOT NULL DEFAULT 'wecon_vnet2',
  external_device_id TEXT NOT NULL,
  machine_code TEXT NOT NULL UNIQUE,
  device_name TEXT NOT NULL,
  device_model TEXT,
  online_state BOOLEAN,
  last_seen_at TIMESTAMPTZ,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT farm_devices_provider_check CHECK (provider = 'wecon_vnet2')
);

CREATE TABLE IF NOT EXISTS public.farm_sensor_tags (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id UUID NOT NULL REFERENCES public.farm_devices(id) ON DELETE CASCADE,
  tag_code TEXT NOT NULL,
  display_name TEXT,
  read_address TEXT,
  communication_port TEXT,
  unit TEXT,
  sensor_kind TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT farm_sensor_tags_device_tag_unique UNIQUE (device_id, tag_code)
);

CREATE TABLE IF NOT EXISTS public.farm_sensor_readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id UUID NOT NULL REFERENCES public.farm_devices(id) ON DELETE CASCADE,
  tag_id UUID NOT NULL REFERENCES public.farm_sensor_tags(id) ON DELETE CASCADE,
  recorded_at TIMESTAMPTZ NOT NULL,
  numeric_value NUMERIC,
  raw_value TEXT,
  quality_status TEXT NOT NULL DEFAULT 'unknown',
  source TEXT NOT NULL DEFAULT 'vnet_history',
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT farm_sensor_readings_quality_check
    CHECK (quality_status IN ('good', 'bad', 'uncertain', 'unknown')),
  CONSTRAINT farm_sensor_readings_source_check
    CHECK (source IN ('vnet_realtime', 'vnet_history', 'manual_import')),
  CONSTRAINT farm_sensor_readings_tag_time_unique UNIQUE (tag_id, recorded_at)
);

CREATE TABLE IF NOT EXISTS public.farm_device_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id UUID NOT NULL REFERENCES public.farm_devices(id) ON DELETE CASCADE,
  event_code TEXT NOT NULL,
  event_label TEXT,
  state TEXT,
  event_at TIMESTAMPTZ NOT NULL,
  source TEXT NOT NULL DEFAULT 'vnet',
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.farm_alarm_records (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id UUID NOT NULL REFERENCES public.farm_devices(id) ON DELETE CASCADE,
  external_alarm_id TEXT,
  monitor_id TEXT,
  alarm_type TEXT,
  alarm_level TEXT,
  state TEXT,
  message TEXT,
  numeric_value NUMERIC,
  occurred_at TIMESTAMPTZ NOT NULL,
  acknowledged_at TIMESTAMPTZ,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.farm_sync_runs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  source TEXT NOT NULL DEFAULT 'wecon_vnet2',
  status TEXT NOT NULL DEFAULT 'running',
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  records_received INTEGER NOT NULL DEFAULT 0,
  records_upserted INTEGER NOT NULL DEFAULT 0,
  error_message TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT farm_sync_runs_status_check
    CHECK (status IN ('running', 'completed', 'partial', 'failed'))
);

CREATE INDEX IF NOT EXISTS idx_farm_sensor_readings_device_time
  ON public.farm_sensor_readings (device_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_farm_sensor_readings_tag_time
  ON public.farm_sensor_readings (tag_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_farm_device_events_device_time
  ON public.farm_device_events (device_id, event_at DESC);
CREATE INDEX IF NOT EXISTS idx_farm_alarm_records_device_time
  ON public.farm_alarm_records (device_id, occurred_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_farm_alarm_records_external_id
  ON public.farm_alarm_records (device_id, external_alarm_id)
  WHERE external_alarm_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_farm_sync_runs_started_at
  ON public.farm_sync_runs (started_at DESC);


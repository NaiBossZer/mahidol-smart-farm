ALTER TABLE public.farm_device_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.farm_alarm_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.farm_sync_runs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read farm devices" ON public.farm_devices;
CREATE POLICY "Authenticated users can read farm devices"
  ON public.farm_devices FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated users can read farm sensor tags" ON public.farm_sensor_tags;
CREATE POLICY "Authenticated users can read farm sensor tags"
  ON public.farm_sensor_tags FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated users can read farm sensor readings" ON public.farm_sensor_readings;
CREATE POLICY "Authenticated users can read farm sensor readings"
  ON public.farm_sensor_readings FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated users can read farm device events" ON public.farm_device_events;
CREATE POLICY "Authenticated users can read farm device events"
  ON public.farm_device_events FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated users can read farm alarm records" ON public.farm_alarm_records;
CREATE POLICY "Authenticated users can read farm alarm records"
  ON public.farm_alarm_records FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated users can read farm sync runs" ON public.farm_sync_runs;
CREATE POLICY "Authenticated users can read farm sync runs"
  ON public.farm_sync_runs FOR SELECT TO authenticated USING (true);

-- Explicit grants are required for Data API exposure on newer Supabase projects.
GRANT SELECT ON public.farm_devices, public.farm_sensor_tags,
  public.farm_sensor_readings, public.farm_device_events,
  public.farm_alarm_records, public.farm_sync_runs TO authenticated;
GRANT ALL PRIVILEGES ON public.farm_devices, public.farm_sensor_tags,
  public.farm_sensor_readings, public.farm_device_events,
  public.farm_alarm_records, public.farm_sync_runs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.farm_sensor_readings_id_seq TO service_role;

COMMENT ON TABLE public.farm_devices IS 'V-NET2.0 Smart Farm HMI devices';
COMMENT ON TABLE public.farm_sensor_tags IS 'Sensor/tag definitions mapped from V-NET2.0';
COMMENT ON TABLE public.farm_sensor_readings IS 'Time-series sensor readings from V-NET2.0';
COMMENT ON TABLE public.farm_device_events IS 'Valve, exhaust, evap, shade, lighting and device state events';
COMMENT ON TABLE public.farm_alarm_records IS 'Alarm history imported from V-NET2.0';
COMMENT ON TABLE public.farm_sync_runs IS 'Audit log for Apps Script V-NET2.0 synchronization runs';
